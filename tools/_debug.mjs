import { chromium } from '@playwright/test';
const res = await fetch('http://localhost:8787/api/rooms', { method: 'POST', headers: { 'content-type': 'application/json', Origin: 'http://localhost:3000' }, body: JSON.stringify({ settings: { game: 'grand-rounds', speed: 0.5 } }) });
const { code, hostToken } = await res.json();
const browser = await chromium.launch({ channel: 'chrome' });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
await ctx.addInitScript(([c, t]) => localStorage.setItem(`iatrome:host:${c}`, t), [code, hostToken]);
const stage = await ctx.newPage();
stage.on('console', (m) => m.type() === 'error' && console.log('ERR', m.text()));
await stage.goto(`http://localhost:3000/host/${code}`);
await stage.waitForTimeout(1500);
for (let i = 0; i < 4; i++) await stage.getByRole('button', { name: /Add a bot/ }).click();
await stage.getByRole('button', { name: /start/i }).click();
await stage.waitForFunction(() => document.querySelector('main')?.dataset.phase === 'playing:vote', null, { timeout: 120000 });
await stage.waitForTimeout(800);
const info = await stage.evaluate(() => {
  const versus = document.querySelector('[class*="versus"]');
  return { versusHTML: versus?.outerHTML.slice(0, 1500), rect: versus?.getBoundingClientRect() };
});
console.log(JSON.stringify(info, null, 1));
await stage.screenshot({ path: '/tmp/iatrome-shots/debug-vote.png' });
await browser.close();
